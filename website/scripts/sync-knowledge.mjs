// Copies the one source of truth for website words (docs/website/chat-knowledge.md, Josh's file)
// into a JS module the Cloudflare Pages Function can import as the chat box's system prompt.
// Run before `astro build` (see package.json "prebuild"). Never edit the output by hand.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../docs/website/chat-knowledge.md');
const out = resolve(here, '../functions/_lib/knowledge.js');

const md = readFileSync(src, 'utf8');
const stamp = (md.match(/—\s*(\d{1,2} \w+ \d{4})/) || [])[1] || 'unknown date';
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/sync-knowledge.mjs from docs/website/chat-knowledge.md (${stamp}). Do not edit.\n` +
    `export const KNOWLEDGE_DATE = ${JSON.stringify(stamp)};\n` +
    `export const KNOWLEDGE = ${JSON.stringify(md)};\n`,
);
console.log(`knowledge synced (${md.length} chars, ${stamp}) -> functions/_lib/knowledge.js`);
